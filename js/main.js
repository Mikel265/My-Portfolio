// Multi-Intent Handler Engine
function getMikiAIResponse(query) {
  const securityCheck = checkSecurityGuardrail(query);
  if (securityCheck) return securityCheck;

  // Split query on question marks or explicit " and " conjunctions when multiple questions exist
  const rawParts = query.split(/\?|\band\b/i).map(p => p.trim()).filter(p => p.length > 2);

  if (rawParts.length > 1) {
    const subResponses = [];
    let hasOffTopic = false;
    let offTopicSubject = "";

    rawParts.forEach((part, index) => {
      const resp = getSingleIntentResponse(part);
      
      // Detect if part was off-topic redirection
      if (resp === "I'm focused on helping you explore Mikel Graphicals and Mikel's portfolio. Ask me about the projects, services, skills, process, pricing, or contact information.") {
        hasOffTopic = true;
        offTopicSubject = part;
      } else if (resp && !subResponses.includes(resp)) {
        subResponses.push(resp);
      }
    });

    if (subResponses.length > 0) {
      if (hasOffTopic) {
        subResponses.push("I can help you explore Mikel's portfolio, but I'm primarily designed to assist with Mikel Graphicals and its work.");
      }
      return subResponses.join("\n\n");
    }
  }

  return getSingleIntentResponse(query);
}

// Instant SPA Page Router (Zero White Flash Navigation)
function initPageTransitions() {
  document.body.classList.add("page-loaded");

  document.addEventListener("click", async (e) => {
    const link = e.target.closest("a");
    if (!link) return;

    const href = link.getAttribute("href");
    if (!href) return;

    if (
      href.startsWith("#") ||
      href.startsWith("mailto:") ||
      href.startsWith("tel:") ||
      href.endsWith(".pdf") ||
      link.target === "_blank" ||
      e.ctrlKey || e.metaKey || e.shiftKey || e.altKey
    ) {
      return;
    }

    const isRelative = !href.includes("://") && !href.startsWith("//");
    const isSameHost = href.includes(window.location.hostname);

    if (isRelative || isSameHost) {
      const currentPath = window.location.pathname.split("/").pop() || "index.html";
      const targetPath = href.split("#")[0].split("/").pop() || "index.html";

      if (currentPath === targetPath && !href.includes("#")) {
        return;
      }

      e.preventDefault();

      try {
        const response = await fetch(href);
        if (!response.ok) {
          window.location.href = href;
          return;
        }

        const htmlText = await response.text();
        const parser = new DOMParser();
        const doc = parser.parseFromString(htmlText, "text/html");

        const newBody = doc.querySelector("body");
        const newTitle = doc.querySelector("title");

        if (newBody) {
          document.body.innerHTML = newBody.innerHTML;
          if (newTitle) document.title = newTitle.innerText;
          window.history.pushState({}, "", href);
          window.scrollTo({ top: 0, behavior: "instant" });

          initAllPageHandlers();
        } else {
          window.location.href = href;
        }
      } catch (err) {
        window.location.href = href;
      }
    }
  });

  window.addEventListener("popstate", () => {
    window.location.reload();
  });
}

